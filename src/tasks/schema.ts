import type { TaskClass } from '../router/classify.ts'
import type { ApprovalMode } from '../run/approvals.ts'
import { validTaskEngineIds } from '../run/executors/task-engines.ts'

export const TASK_ID_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/

const TASK_CLASSES: readonly TaskClass[] = ['plan', 'implement', 'fix', 'review', 'doc']

export function isTaskClass(value: unknown): value is TaskClass {
  return typeof value === 'string' && (TASK_CLASSES as readonly string[]).includes(value)
}

const TASK_STATUSES = [
  'pending',
  'running',
  'done',
  'failed',
  'failed_permanent',
  'blocked',
] as const
export type TaskStatus = (typeof TASK_STATUSES)[number]
const QA_VERDICTS = ['pass', 'fail', 'skipped'] as const
export type TaskExecutor = 'openrouter' | 'anthropic' | 'openai' | 'codex'
// B.2 — 'external' es la tercera implementación de ExecutorEngine (B.1, docs/done/design/external-executor-design.md).
// Lanza el subproceso `claude -p` dentro del worktree; el harness aplica enforceContract post-hoc
// igual que con single-shot/agentic. Opt-in por tarea o por config de proyecto.
// Los ids de motores de CLI viven en el registro (`run/executors/task-engines.ts`) y se validan en runtime.
export type TaskEngine = 'single-shot' | 'agentic' | (string & {})

const EXECUTORS: TaskExecutor[] = ['openrouter', 'anthropic', 'openai', 'codex']

// Los niveles pertenecen al engine que los interpreta. `external` usa el contrato
// de Claude Code; `codex` usa los valores de `model_reasoning_effort`. Los engines
// sin contrato verificado, incluido opencode, quedan deliberadamente fuera.
export const CLI_EFFORT_LEVELS = {
  external: ['low', 'medium', 'high', 'xhigh', 'max'],
  codex: ['minimal', 'low', 'medium', 'high', 'xhigh', 'max', 'ultra'],
} as const

export type CliEffort = (typeof CLI_EFFORT_LEVELS)[keyof typeof CLI_EFFORT_LEVELS][number]

export interface Check {
  cmd: string
  cwd?: string
  timeout_ms?: number
  expect_exit?: number
  /** Internal checks generated by OrchestOS may use trusted absolute tool paths. */
  trusted?: boolean
}

export interface Task {
  id: string // kebab-case, unique within file
  description: string
  skill?: string // skill id from skills/
  executor: TaskExecutor
  /** Per-task model override — wins over orchestos.config.yaml executor_heavy/light role */
  executor_model?: string
  /** Per-task planner model — for future sub-agent planning step */
  planner_model?: string
  /** Which ExecutorEngine runs this task — undefined resolves via orchestos.config.yaml, default 'single-shot' (G.3) */
  engine?: TaskEngine
  /** Optional action approval policy; absent keeps full until ERP.7.1c. */
  approvalMode?: ApprovalMode
  /** Chosen by the user and interpreted by the selected CLI. */
  cli_effort?: string
  /** Clase declarada al crear la tarea; sin ella el harness clasifica por la descripción. */
  task_class?: TaskClass
  input: string[] // files the LLM can read (relative to project root)
  output: string[] // files the LLM is allowed to write — REQUIRED, must be non-empty
  acceptance_criteria?: string[]
  checks?: Check[]
  depends_on: string[] // task ids that must be done first
  status: TaskStatus
  retry_count: number
  retry_reason?: string // last QA fail reason
  qa_verdict?: 'pass' | 'fail' | 'skipped'
  run_id?: string // last SQLite run id
}

export interface TasksFile {
  version: 1
  project: string
  tasks: Task[]
}

export function validateTask(t: unknown, index: number): Task {
  const err = (msg: string) => {
    throw new Error(`tasks.yaml[${index}]: ${msg}`)
  }
  const task = t as Record<string, unknown>

  if (!task.id || typeof task.id !== 'string') err('missing "id"')
  if (!TASK_ID_RE.test(task.id as string)) err(`id must be kebab-case, got: ${task.id}`)
  if (!task.description || typeof task.description !== 'string') err('missing "description"')
  if (!Array.isArray(task.output) || (task.output as unknown[]).length === 0)
    err('"output" must be a non-empty array — this is the contract')
  const output = validateStringArray(task.output, 'output', err) as string[]

  const executor = validateExecutor(task.executor, err)

  return {
    id: task.id as string,
    description: task.description as string,
    skill: typeof task.skill === 'string' ? task.skill : undefined,
    executor,
    executor_model: typeof task.executor_model === 'string' ? task.executor_model : undefined,
    planner_model: typeof task.planner_model === 'string' ? task.planner_model : undefined,
    engine: validateEngine(task.engine, err),
    approvalMode: validateApprovalMode(task.approvalMode, err),
    cli_effort: validateCliEffort(task.cli_effort, task.engine, err),
    task_class: validateTaskClass(task.task_class, err),
    input: validateStringArray(optionalList(task.input), 'input', err) ?? [],
    output,
    acceptance_criteria: validateStringArray(task.acceptance_criteria, 'acceptance_criteria', err),
    checks: validateChecks(task.checks, err),
    depends_on: validateStringArray(optionalList(task.depends_on), 'depends_on', err) ?? [],
    status: validateMember(task.status, TASK_STATUSES, 'status', err) ?? 'pending',
    retry_count: typeof task.retry_count === 'number' ? task.retry_count : 0,
    retry_reason: typeof task.retry_reason === 'string' ? task.retry_reason : undefined,
    qa_verdict: validateMember(task.qa_verdict, QA_VERDICTS, 'qa_verdict', err),
    run_id: typeof task.run_id === 'string' ? task.run_id : undefined,
  }
}

function validateExecutor(value: unknown, err: (msg: string) => never): TaskExecutor {
  if (value === undefined) return 'openrouter'
  if (typeof value !== 'string' || !EXECUTORS.includes(value as TaskExecutor)) {
    err(`unknown executor '${String(value)}' — allowed: ${EXECUTORS.join(', ')}`)
  }
  if (value === 'codex' && process.env.OS_ENABLE_EXEC_CODEX !== '1') {
    err('codex executor disabled — set OS_ENABLE_EXEC_CODEX=1 to enable')
  }
  return value as TaskExecutor
}

function validateTaskClass(value: unknown, err: (msg: string) => never): TaskClass | undefined {
  if (value === undefined) return undefined
  if (!isTaskClass(value))
    err(`unknown task_class '${String(value)}' — allowed: ${TASK_CLASSES.join(', ')}`)
  return value as TaskClass
}

function validateEngine(value: unknown, err: (msg: string) => never): TaskEngine | undefined {
  if (value === undefined) return undefined
  if (typeof value !== 'string' || !validTaskEngineIds().includes(value)) {
    err(`unknown engine '${String(value)}' — allowed: ${validTaskEngineIds().join(', ')}`)
  }
  return value as TaskEngine
}

function validateCliEffort(
  value: unknown,
  _engine: unknown,
  err: (msg: string) => never,
): string | undefined {
  if (value === undefined) return undefined
  if (typeof value !== 'string' || value.trim() === '') err('cli_effort must be a non-empty string')
  return value.trim()
}

function validateStringArray(
  value: unknown,
  field: string,
  err: (msg: string) => never,
): string[] | undefined {
  if (value === undefined) return undefined
  if (!Array.isArray(value)) err(`"${field}" must be an array of strings`)
  const strings = value as unknown[]
  for (const [i, item] of strings.entries()) {
    if (typeof item !== 'string' || item.trim() === '') {
      err(`"${field}[${i}]" must be a non-empty string`)
    }
  }
  return strings as string[]
}

/** `null` en YAML (`input:` vacío) equivale a no declarar la lista. */
function optionalList(value: unknown): unknown {
  return value === null ? undefined : value
}

function validateMember<T extends string>(
  value: unknown,
  allowed: readonly T[],
  field: string,
  err: (msg: string) => never,
): T | undefined {
  if (value === undefined || value === null) return undefined
  if (typeof value !== 'string' || !(allowed as readonly string[]).includes(value)) {
    err(`unknown ${field} '${String(value)}' — allowed: ${allowed.join(', ')}`)
  }
  return value as T
}

function validateCheckNumber(
  value: unknown,
  field: string,
  min: number,
  err: (msg: string) => never,
): number | undefined {
  if (value === undefined) return undefined
  if (typeof value !== 'number' || !Number.isInteger(value) || value < min) {
    err(`"${field}" must be an integer >= ${min}`)
  }
  return value
}

function validateChecks(value: unknown, err: (msg: string) => never): Check[] | undefined {
  if (value === undefined) return undefined
  if (!Array.isArray(value)) err('"checks" must be an array')

  return (value as unknown[]).map((item, i) => {
    const check = typeof item === 'string' ? { cmd: item } : (item as Record<string, unknown>)
    if (typeof check !== 'object' || check === null || Array.isArray(check)) {
      err(`"checks[${i}]" must be a string command or an object`)
    }
    if (typeof check.cmd !== 'string' || check.cmd.trim() === '') {
      err(`"checks[${i}].cmd" is required`)
    }
    validateCheckCommand(check.cmd, `checks[${i}].cmd`, err)
    if (check.cwd !== undefined && typeof check.cwd !== 'string') {
      err(`"checks[${i}].cwd" must be a string`)
    }
    return {
      cmd: check.cmd.trim(),
      cwd: typeof check.cwd === 'string' ? check.cwd : undefined,
      timeout_ms: validateCheckNumber(check.timeout_ms, `checks[${i}].timeout_ms`, 1, err),
      expect_exit: validateCheckNumber(check.expect_exit, `checks[${i}].expect_exit`, 0, err),
    }
  })
}

function validateCheckCommand(cmd: string, field: string, err: (msg: string) => never): void {
  const blocked = ['&&', '||', ';', '`', '$(']
  for (const token of blocked) {
    if (cmd.includes(token)) {
      err(
        `"${field}" cannot contain shell metacharacter "${token}" — declare separate checks instead`,
      )
    }
  }
}

export function validateTasksFile(raw: unknown): TasksFile {
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) {
    throw new Error('tasks.yaml: root must be a mapping')
  }
  const f = raw as Record<string, unknown>
  if (!f.project || typeof f.project !== 'string') throw new Error('tasks.yaml: missing "project"')
  if (!Array.isArray(f.tasks)) throw new Error('tasks.yaml: missing "tasks" array')

  const tasks = (f.tasks as unknown[]).map((t, i) => validateTask(t, i))

  // check duplicate ids
  const ids = tasks.map((t) => t.id)
  const dupes = ids.filter((id, i) => ids.indexOf(id) !== i)
  if (dupes.length > 0) throw new Error(`tasks.yaml: duplicate task ids: ${dupes.join(', ')}`)

  return { version: 1, project: f.project as string, tasks }
}

function validateApprovalMode(
  value: unknown,
  err: (msg: string) => never,
): ApprovalMode | undefined {
  if (value === undefined) return undefined
  if (value !== 'full' && value !== 'supervised' && value !== 'auto-edit')
    err('unknown approvalMode')
  return value as ApprovalMode
}
